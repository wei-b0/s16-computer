//! Code generation: typed IR -> S16 assembly text.
//!
//! Deliberately naive and uniform (COMPILER.md pins behavior, not quality):
//! every value lives in a frame slot, expressions evaluate into R12 with the
//! stack for intermediates, every function gets the standard ABI frame from
//! CALLING_CONVENTION.md. Label scheme: `F_` functions, `G_` statics, `L{n}`
//! generated labels — user identifiers can never collide.

use crate::ast::{BinOp, Scalar, UnOp};
use crate::check::{Builtin, Program, TExpr, TExprKind, TFn, TStmt};
use std::fmt::Write;

pub fn generate(program: &Program) -> String {
    let mut g = Gen { out: String::new(), labels: 0, loops: Vec::new(), fun: None };
    g.line("; generated by s16c");
    g.emit("CALL F_main");
    g.emit("HALT");
    for f in &program.fns {
        g.function(f);
    }
    if !program.statics.is_empty() {
        g.line("");
        g.line("; data");
        for s in &program.statics {
            let words: Vec<String> = s.words.iter().map(|w| format!("0x{w:04X}")).collect();
            g.line(&format!("G_{}: .word {}", s.name, words.join(", ")));
        }
    }
    g.out
}

struct Frame {
    arg_stage: usize,
}

struct Gen {
    out: String,
    labels: usize,
    /// (continue_label, break_label) per enclosing loop.
    loops: Vec<(String, String)>,
    fun: Option<Frame>,
}

impl Gen {
    fn line(&mut self, s: &str) {
        let _ = writeln!(self.out, "{s}");
    }

    fn emit(&mut self, s: &str) {
        let _ = writeln!(self.out, "        {s}");
    }

    fn label(&mut self) -> String {
        self.labels += 1;
        format!("L{}", self.labels)
    }

    fn place_label(&mut self, l: &str) {
        let _ = writeln!(self.out, "{l}:");
    }

    /// Frame offset of a slot: slot i lives at [R15 - 2*(i+1)].
    fn slot_off(&self, slot: usize) -> String {
        format!("[R15-{}]", 2 * (slot + 1))
    }

    fn function(&mut self, f: &TFn) {
        self.fun = Some(Frame { arg_stage: f.arg_stage });
        self.line("");
        self.line(&format!("F_{}:", f.name));
        self.emit("PUSH R15");
        self.emit("RSP  R15");
        if f.nslots > 0 {
            self.emit(&format!("SUBI R12, R15, #{}", 2 * f.nslots));
            self.emit("WSP  R12");
        }
        // Spill incoming parameters to their slots.
        for i in 0..f.nparams.min(4) {
            let off = self.slot_off(i);
            self.emit(&format!("STW  {off}, R{i}"));
        }
        for i in 4..f.nparams {
            let stack_off = 4 + 2 * (i - 4);
            let off = self.slot_off(i);
            self.emit(&format!("LDW  R12, [R15+{stack_off}]"));
            self.emit(&format!("STW  {off}, R12"));
        }
        self.stmts(&f.body);
        self.epilogue(); // unreachable for must-return functions; harmless
    }

    fn epilogue(&mut self) {
        self.emit("WSP  R15");
        self.emit("POP  R15");
        self.emit("RET");
    }

    fn stmts(&mut self, body: &[TStmt]) {
        for s in body {
            self.stmt(s);
        }
    }

    fn stmt(&mut self, s: &TStmt) {
        match s {
            TStmt::Store { slot, value } => {
                self.expr(value);
                let off = self.slot_off(*slot);
                self.emit(&format!("STW  {off}, R12"));
            }
            TStmt::StoreStatic { name, value } => {
                self.expr(value);
                self.emit(&format!("LDI  R14, #G_{name}"));
                self.emit("STW  [R14], R12");
            }
            TStmt::StoreIndex { name, index, value } => {
                self.expr(index);
                self.emit("SHLI R12, R12, #1");
                self.emit("PUSH R12");
                self.expr(value);
                self.emit("MOV  R13, R12");
                self.emit("POP  R12");
                self.emit(&format!("LDI  R14, #G_{name}"));
                self.emit("ADD  R14, R14, R12");
                self.emit("STW  [R14], R13");
            }
            TStmt::If { cond, then, els } => {
                let l_end = self.label();
                let l_else = if els.is_empty() { l_end.clone() } else { self.label() };
                self.expr(cond);
                self.emit("CMPI R12, #0");
                self.emit(&format!("BEQ  {l_else}"));
                self.stmts(then);
                if !els.is_empty() {
                    self.emit(&format!("JMP  {l_end}"));
                    self.place_label(&l_else);
                    self.stmts(els);
                }
                self.place_label(&l_end);
            }
            TStmt::While { cond, body } => {
                let l_top = self.label();
                let l_end = self.label();
                self.place_label(&l_top);
                self.expr(cond);
                self.emit("CMPI R12, #0");
                self.emit(&format!("BEQ  {l_end}"));
                self.loops.push((l_top.clone(), l_end.clone()));
                self.stmts(body);
                self.loops.pop();
                self.emit(&format!("JMP  {l_top}"));
                self.place_label(&l_end);
            }
            TStmt::Loop { body } => {
                let l_top = self.label();
                let l_end = self.label();
                self.place_label(&l_top);
                self.loops.push((l_top.clone(), l_end.clone()));
                self.stmts(body);
                self.loops.pop();
                self.emit(&format!("JMP  {l_top}"));
                self.place_label(&l_end);
            }
            TStmt::Break => {
                let target = self.loops.last().unwrap().1.clone();
                self.emit(&format!("JMP  {target}"));
            }
            TStmt::Continue => {
                let target = self.loops.last().unwrap().0.clone();
                self.emit(&format!("JMP  {target}"));
            }
            TStmt::Return(value) => {
                if let Some(v) = value {
                    self.expr(v);
                    self.emit("MOV  R0, R12");
                }
                self.epilogue();
            }
            TStmt::Expr(e) => self.expr(e),
        }
    }

    /// Evaluate into R12. May use R13/R14 and balanced pushes.
    fn expr(&mut self, e: &TExpr) {
        match &e.kind {
            TExprKind::Int(v) => self.emit(&format!("LDI  R12, #0x{v:04X}")),
            TExprKind::Local(slot) => {
                let off = self.slot_off(*slot);
                self.emit(&format!("LDW  R12, {off}"));
            }
            TExprKind::Static(name) => {
                self.emit(&format!("LDI  R14, #G_{name}"));
                self.emit("LDW  R12, [R14]");
            }
            TExprKind::Index(name, idx) => {
                self.expr(idx);
                self.emit("SHLI R12, R12, #1");
                self.emit(&format!("LDI  R14, #G_{name}"));
                self.emit("ADD  R14, R14, R12");
                self.emit("LDW  R12, [R14]");
            }
            TExprKind::Unary(UnOp::Neg, inner) => {
                self.expr(inner);
                self.emit("MOV  R13, R12");
                self.emit("LDI  R12, #0");
                self.emit("SUB  R12, R12, R13");
            }
            TExprKind::Unary(UnOp::Not, inner) => {
                let is_bool = inner.ty == Some(Scalar::Bool);
                self.expr(inner);
                if is_bool {
                    self.emit("XORI R12, R12, #1");
                } else {
                    self.emit("NOT  R12, R12");
                }
            }
            TExprKind::Binary { op: BinOp::LogAnd, lhs, rhs, .. } => {
                let l_end = self.label();
                self.expr(lhs);
                self.emit("CMPI R12, #0");
                self.emit(&format!("BEQ  {l_end}")); // false: R12 already 0
                self.expr(rhs);
                self.place_label(&l_end);
            }
            TExprKind::Binary { op: BinOp::LogOr, lhs, rhs, .. } => {
                let l_end = self.label();
                self.expr(lhs);
                self.emit("CMPI R12, #0");
                self.emit(&format!("BNE  {l_end}")); // true: R12 already 1
                self.expr(rhs);
                self.place_label(&l_end);
            }
            TExprKind::Binary { op, operands, lhs, rhs } if op.is_compare() => {
                self.binary_operands(lhs, rhs);
                let signed = *operands == Scalar::I16;
                // The ISA has <, >=, == branches; > and <= swap operands.
                let (cmp, branch) = match (op, signed) {
                    (BinOp::Eq, _) => ("CMP  R12, R13", "BEQ"),
                    (BinOp::Ne, _) => ("CMP  R12, R13", "BNE"),
                    (BinOp::Lt, false) => ("CMP  R12, R13", "BLTU"),
                    (BinOp::Lt, true) => ("CMP  R12, R13", "BLT"),
                    (BinOp::Ge, false) => ("CMP  R12, R13", "BGEU"),
                    (BinOp::Ge, true) => ("CMP  R12, R13", "BGE"),
                    (BinOp::Gt, false) => ("CMP  R13, R12", "BLTU"),
                    (BinOp::Gt, true) => ("CMP  R13, R12", "BLT"),
                    (BinOp::Le, false) => ("CMP  R13, R12", "BGEU"),
                    (BinOp::Le, true) => ("CMP  R13, R12", "BGE"),
                    _ => unreachable!(),
                };
                let l_true = self.label();
                self.emit(cmp);
                self.emit("LDI  R12, #1"); // LDI does not touch FLAGS
                self.emit(&format!("{branch} {l_true}"));
                self.emit("LDI  R12, #0");
                self.place_label(&l_true);
            }
            TExprKind::Binary { op, operands, lhs, rhs } => {
                self.binary_operands(lhs, rhs);
                let signed = *operands == Scalar::I16;
                let instr = match op {
                    BinOp::Add => "ADD ",
                    BinOp::Sub => "SUB ",
                    BinOp::Mul => "MUL ",
                    BinOp::Div => "DIV ",
                    BinOp::Mod => "MOD ",
                    BinOp::BitAnd => "AND ",
                    BinOp::BitOr => "OR  ",
                    BinOp::BitXor => "XOR ",
                    BinOp::Shl => "SHL ",
                    BinOp::Shr if signed => "SAR ",
                    BinOp::Shr => "SHR ",
                    _ => unreachable!(),
                };
                self.emit(&format!("{instr} R12, R12, R13"));
            }
            TExprKind::Builtin(b, args) => self.builtin(*b, args),
            TExprKind::Call(name, args) => self.call(name, args),
        }
    }

    /// Evaluate lhs and rhs, leaving lhs in R12 and rhs in R13.
    fn binary_operands(&mut self, lhs: &TExpr, rhs: &TExpr) {
        self.expr(lhs);
        self.emit("PUSH R12");
        self.expr(rhs);
        self.emit("MOV  R13, R12");
        self.emit("POP  R12");
    }

    fn builtin(&mut self, b: Builtin, args: &[TExpr]) {
        match b {
            Builtin::Halt => self.emit("HALT"),
            Builtin::Brk => self.emit("BRK"),
            Builtin::Peek | Builtin::Peek8 => {
                self.expr(&args[0]);
                let load = if b == Builtin::Peek { "LDW " } else { "LDB " };
                self.emit(&format!("{load} R12, [R12]"));
            }
            Builtin::Poke | Builtin::Poke8 => {
                self.expr(&args[0]);
                self.emit("PUSH R12");
                self.expr(&args[1]);
                self.emit("MOV  R13, R12");
                self.emit("POP  R12");
                let store = if b == Builtin::Poke { "STW " } else { "STB " };
                self.emit(&format!("{store} [R12], R13"));
            }
        }
    }

    /// Calls stage arguments through frame slots so nested calls can't
    /// clobber each other: evaluate left-to-right onto the stack, unstack
    /// into the staging slots, then load registers / push stack args from
    /// the slots (no nested evaluation in that final phase).
    fn call(&mut self, name: &str, args: &[TExpr]) {
        let stage = self.fun.as_ref().unwrap().arg_stage;
        for a in args {
            self.expr(a);
            self.emit("PUSH R12");
        }
        for i in (0..args.len()).rev() {
            let off = self.slot_off(stage + i);
            self.emit("POP  R12");
            self.emit(&format!("STW  {off}, R12"));
        }
        // Stack arguments (5th onward), pushed right to left.
        for i in (4..args.len()).rev() {
            let off = self.slot_off(stage + i);
            self.emit(&format!("LDW  R12, {off}"));
            self.emit("PUSH R12");
        }
        for (i, _) in args.iter().enumerate().take(4) {
            let off = self.slot_off(stage + i);
            self.emit(&format!("LDW  R{i}, {off}"));
        }
        self.emit(&format!("CALL F_{name}"));
        if args.len() > 4 {
            let bytes = 2 * (args.len() - 4);
            self.emit("RSP  R13");
            self.emit(&format!("ADDI R13, R13, #{bytes}"));
            self.emit("WSP  R13");
        }
        self.emit("MOV  R12, R0");
    }
}
